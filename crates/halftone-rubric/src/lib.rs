//! C2PA asset rubrics, evaluated natively.
//!
//! The C2PA publishes rubrics that classify what a manifest *declares* (C2PA Asset
//! Rubrics 1.0, c2pa-org/conformance-public). The signals rubric labels each
//! manifest in a provenance chain with inception signals (captured media, fully
//! GenAI media, ...) and transformation signals (perceptible GenAI edit,
//! non-editorial, ambiguous actions, ...). It is written in json-formula and run by
//! the C2PA's Python evaluator over crJSON.
//!
//! This crate runs that rubric file **unmodified** ([`SIGNALS_LOCAL_YAML`],
//! pinned by [`SIGNALS_LOCAL_SHA256`]) with a native json-formula interpreter
//! ([`formula`]) and a port of the reference evaluator ([`signals`]). Fidelity is a
//! test, not a claim: the golden fixtures in `testdata/rubric-signals/` are the
//! reference evaluator's own output, regenerated by `scripts/rubric-golden.py`.
//!
//! A signal is a statement about what the signer declared, not a verification:
//! callers report it next to the manifest's validation state, never instead of it.

pub mod formula;
pub mod rubric;
pub mod signals;
pub mod value;

pub use rubric::Rubric;
pub use signals::{SignalsReport, StatementError};
pub use value::JValue;

/// The C2PA Asset Signals Rubric (Local) 1.0, byte for byte as published (CC BY 4.0;
/// see `rubrics/NOTICE.md`).
pub const SIGNALS_LOCAL_YAML: &str = include_str!("../rubrics/asset-rubric-signals-local.yml");

/// SHA-256 of [`SIGNALS_LOCAL_YAML`] as published in c2pa-org/conformance-public at
/// commit `da71a72`.
pub const SIGNALS_LOCAL_SHA256: &str =
    "0502e989e025b32a0b253645991abf56d2cd14860a1e7cda10e6921bc5ba19a8";

/// Load the vendored signals rubric.
pub fn signals_local() -> Result<Rubric, formula::Error> {
    Rubric::from_yaml(SIGNALS_LOCAL_YAML)
}
